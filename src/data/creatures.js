// LUMENFALL — Kindred species data: the 48 canonical Kindred + XP curves.
// Stat budgets (sum of base.vigor/might/ward/focus/aegis/haste):
//   stage1 ~275, stage2 ~340, stage3 ~410, legendary ~480, single-stage species +4%.
// budgetStats() distributes a personality-weighted spread that always sums exactly to budget.

function budgetStats(budget, w) {
  const keys = ['vigor', 'might', 'ward', 'focus', 'aegis', 'haste'];
  const sum = keys.reduce((s, k) => s + (w[k] ?? 1), 0);
  const raw = keys.map((k) => ((w[k] ?? 1) / sum) * budget);
  const rounded = raw.map(Math.round);
  const drift = budget - rounded.reduce((a, b) => a + b, 0);
  let idx = 0, maxW = -1;
  keys.forEach((k, i) => { if ((w[k] ?? 1) > maxW) { maxW = w[k] ?? 1; idx = i; } });
  rounded[idx] += drift;
  const out = {};
  keys.forEach((k, i) => { out[k] = rounded[i]; });
  return out;
}

const BUDGET = { 1: 275, 2: 340, 3: 410, L: 480, single: Math.round(275 * 1.04) };

// XP curve: cumulative xp required to REACH each level (index 0 = level 1 = 0 xp), 1..50.
function curve(mult) {
  const arr = [0];
  for (let l = 2; l <= 50; l++) arr.push(Math.round(mult * Math.pow(l, 3)));
  return arr;
}
export const XP_CURVES = { fast: curve(0.75), medium: curve(1.0), slow: curve(1.3) };

// species-def helper: fills base stats from budget+weights, keeps entries compact & readable.
function S(def) {
  const budget = def.legendary ? BUDGET.L : def.single ? BUDGET.single : BUDGET[def.stage];
  return {
    id: def.id, name: def.name, aspects: def.aspects, stage: def.stage,
    rarity: def.rarity, base: budgetStats(budget, def.w), growth: def.growth,
    awakensTo: def.awakensTo ?? null, learnset: def.learnset,
    trait: def.trait, burst: def.burst, size: def.size, cry: def.cry,
    codex: def.codex, habitat: def.habitat,
  };
}

